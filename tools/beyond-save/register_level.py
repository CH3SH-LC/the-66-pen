"""Register a new Miliastra level by editing the local save, reversibly.

WHAT THIS IS, AND WHAT IT IS NOT
    This writes the game's own files. It is emphatically NOT an editor API call --
    the interface survey found no command, channel or bridge operation that creates
    a level, and this script does not pretend to be one. What it does instead is
    build the same bytes the game itself writes, which is possible only because
    gil_container.py round-trips those bytes exactly.

    Because it edits a live save, it is built around two rules:

      1. Nothing is written until a backup of both the profile and the level
         directory exists and has been read back and compared.
      2. --plan is the default. Writing needs --apply.

    Everything it writes is regenerated by re-encoding fields it parsed from the
    real files, so unknown fields survive; see build_level / build_profile.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools/compatibility"))
from version_guard import IncompatibleVersion, require_compatible  # noqa: E402

from gil_container import (  # noqa: E402
    Container,
    ContainerError,
    Field,
    WIRE_LENGTH,
    WIRE_VARINT,
    add_level_to_profile,
    build_level_ref,
    build_profile,
    decode_container,
    encode_container,
    encode_fields,
    next_level_id,
    parse_fields,
    parse_profile,
    read_level,
    read_profile,
)

GAME_DATA = Path.home() / "AppData" / "LocalLow" / "miHoYo" / "原神" / "BeyondLocal"
DEFAULT_UID = "100000001"
BACKUP_ROOT = Path(__file__).resolve().parents[2] / ".runtime" / "beyond-save" / "backups"

# Field numbers a fresh level needs, taken from the placeholder levels the game
# itself writes: 34 and 41 are constant 1 in every file seen, and 42 appears in
# the two oldest ones. Nothing here is invented; see the note in gil_container.py.
TEMPLATE_FIELDS = ((34, 1), (41, 1), (42, 1))


@dataclass
class Plan:
    uid_dir: Path
    level_path: Path
    level_payload: bytes
    profile_path: Path
    profile_payload: bytes
    level_id: int
    name: str
    backup_dir: Path

    def describe(self) -> dict:
        return {
            "uidDir": str(self.uid_dir),
            "levelId": self.level_id,
            "levelName": self.name,
            "levelFile": str(self.level_path),
            "levelBytes": len(self.level_payload),
            "profileFile": str(self.profile_path),
            "profileBytes": len(self.profile_payload),
            "backupDir": str(self.backup_dir),
        }


# Fields this script sets itself. Everything else the template carries is kept.
IDENTITY_FIELDS = (1, 2, 39, 40)


def build_new_level(template_payload: bytes, level_id: int, name: str, uid: int, timestamp: int) -> bytes:
    """Build a level payload from a template plus the fields that identify it.

    The template supplies whatever else the game expects; only the id, name,
    creator and timestamp are set. Fields are written in ascending order because
    that is the order the game's own writer uses -- see the hexdump of any 79-byte
    level file, where they run 1, 2, 34, 39, 40, 41, 42.
    """
    fields = [f for f in parse_fields(template_payload) if f.number not in IDENTITY_FIELDS]
    fields.append(Field(1, WIRE_VARINT, value=level_id))
    fields.append(Field(2, WIRE_LENGTH, data=name.encode("utf-8")))
    fields.append(Field(39, WIRE_VARINT, value=uid))
    fields.append(Field(40, WIRE_VARINT, value=timestamp))
    return encode_fields(sorted(fields, key=lambda f: f.number))


def plan_registration(
    name: str,
    uid: str = DEFAULT_UID,
    level_id: int | None = None,
    uid_dir: Path | None = None,
    backup_root: Path = BACKUP_ROOT,
    now: int | None = None,
    tab_name: str | None = None,
) -> Plan:
    uid_dir = uid_dir or (GAME_DATA / uid)
    profile_path = uid_dir / "Beyond_Local_Save_Player.gip"
    level_dir = uid_dir / "Beyond_Local_Save_Level"

    if not profile_path.exists():
        raise FileNotFoundError(f"no player profile at {profile_path}")
    levels = sorted(level_dir.glob("*.gil"))
    if not levels:
        raise FileNotFoundError(f"no level files under {level_dir}")

    profile_payload = decode_container(profile_path.read_bytes()).payload
    profile = parse_profile(profile_payload)

    level_id = level_id if level_id is not None else next_level_id(profile)
    if any(ref.level_id == level_id for ref in profile.levels):
        raise ContainerError(f"profile already lists level {level_id}")
    if (level_dir / f"{level_id}.gil").exists():
        raise ContainerError(f"{level_id}.gil already exists")

    # Smallest level file: it is the shape the game writes for a placeholder, so it
    # carries exactly the fields a new level needs and nothing that has to be
    # explained away.
    template = min(levels, key=lambda p: p.stat().st_size).read_bytes()
    template_payload = decode_container(template).payload
    timestamp = now if now is not None else int(time.time())

    level_payload = build_new_level(template_payload, level_id, name, int(uid), timestamp)

    # Registered in both places the profile lists a level: the flat list AND a tab.
    # A flat-list-only entry is invisible to the tab view -- see add_level_to_profile.
    tab = add_level_to_profile(profile, level_id, name, timestamp, tab_name=tab_name)
    profile_payload_new = build_profile(profile)

    return Plan(
        uid_dir=uid_dir,
        level_path=level_dir / f"{level_id}.gil",
        level_payload=level_payload,
        profile_path=profile_path,
        profile_payload=profile_payload_new,
        level_id=level_id,
        name=name,
        backup_dir=backup_root / (
            time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(timestamp)) + f"-register-{level_id}"
        ),
    )


def take_backup(plan: Plan) -> dict:
    """Copy the profile and the whole level directory aside, then verify the copies."""
    if plan.backup_dir.exists():
        raise FileExistsError(f"backup directory already exists: {plan.backup_dir}")
    (plan.backup_dir).mkdir(parents=True)
    profile_copy = plan.backup_dir / plan.profile_path.name
    shutil.copy2(plan.profile_path, profile_copy)
    level_dir_copy = plan.backup_dir / "Beyond_Local_Save_Level"
    shutil.copytree(plan.profile_path.parent / "Beyond_Local_Save_Level", level_dir_copy)

    if profile_copy.read_bytes() != plan.profile_path.read_bytes():
        raise IOError("backup of the profile does not match the original")
    originals = sorted(p.name for p in (plan.profile_path.parent / "Beyond_Local_Save_Level").glob("*"))
    copies = sorted(p.name for p in level_dir_copy.glob("*"))
    if originals != copies:
        raise IOError(f"level directory backup is incomplete: {originals} vs {copies}")

    return {
        "backupDir": str(plan.backup_dir),
        "profile": str(profile_copy),
        "levels": str(level_dir_copy),
        "levelCount": len(copies),
    }


def stage_registration(plan: Plan, out_dir: Path) -> dict:
    """Write the registered files into the project tree instead of the live save.

    This is the default path, not a fallback. AGENT.md's rule for this project is
    "read the original only; write candidates into the project directory, never
    overwrite in place", and a running game rewrites its profile when it next saves,
    so an edit made under it can vanish or collide. Staging produces exactly the
    bytes that would be written, verifies them through the real parsers, and leaves
    the decision to place them with the user.
    """
    out_dir = Path(out_dir)
    level_dir = out_dir / "Beyond_Local_Save_Level"
    level_dir.mkdir(parents=True, exist_ok=True)

    staged_level = level_dir / f"{plan.level_id}.gil"
    staged_profile = out_dir / plan.profile_path.name
    staged_level.write_bytes(encode_container(Container(subtype=2, payload=plan.level_payload)))
    staged_profile.write_bytes(encode_container(Container(subtype=1, payload=plan.profile_payload)))

    level = read_level(staged_level)
    profile = read_profile(staged_profile)
    listed = [ref for ref in profile.levels if ref.level_id == plan.level_id]
    filed_under = [tab.name for tab in profile.tabs if any(lid == plan.level_id for _, lid in tab.members)]
    return {
        "stagedDir": str(out_dir),
        "stagedLevel": str(staged_level),
        "stagedLevelBytes": staged_level.stat().st_size,
        "stagedProfile": str(staged_profile),
        "stagedProfileBytes": staged_profile.stat().st_size,
        "levelId": level.level_id,
        "levelName": level.name,
        "levelCreatorUid": level.creator_uid,
        # Both, because the flat list and the tab list are how the editor finds a
        # level; a candidate that writes only one of them reads back as half-present.
        "profileListsLevel": bool(listed),
        "profileLevelCount": len(profile.levels),
        "filedUnderTabs": filed_under,
        "tabCount": len(profile.tabs),
        "liveSaveUntouched": ReadOnlyEvidence(plan),
    }


def ReadOnlyEvidence(plan: Plan) -> bool:
    """True when the live save still parses and does not list the new level."""
    profile = read_profile(plan.profile_path)
    return all(ref.level_id != plan.level_id for ref in profile.levels)


def apply_registration(plan: Plan) -> dict:
    """Write the new level, then the profile. Order matters: see the note below.

    The level file is written first. If the profile is written and the process dies
    before the level exists, the editor is left pointing at a file that is not
    there; the reverse leaves an unreferenced level, which the game ignores. The
    second failure is the recoverable one.
    """
    require_compatible("all")
    plan.level_path.write_bytes(encode_container(Container(subtype=2, payload=plan.level_payload)))
    require_compatible("all")  # Recheck immediately before each formal-file write.
    plan.profile_path.write_bytes(encode_container(Container(subtype=1, payload=plan.profile_payload)))

    # Read both back through the real parsers, not through the bytes we just wrote.
    return verify_registration(plan)


def verify_registration(plan: Plan) -> dict:
    level = read_level(plan.level_path)
    profile = parse_profile(decode_container(plan.profile_path.read_bytes()).payload)
    listed = [ref for ref in profile.levels if ref.level_id == plan.level_id]
    return {
        "levelId": level.level_id,
        "levelName": level.name,
        "levelCreatorUid": level.creator_uid,
        "levelTimestamp": level.timestamp,
        "profileListsLevel": bool(listed),
        "profileLevelName": listed[0].name if listed else None,
        "profileLevelCount": len(profile.levels),
    }


def _main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", default="demo_关卡_1", help="level name as the editor will show it")
    ap.add_argument("--uid", default=DEFAULT_UID)
    ap.add_argument("--tab", default=None,
                    help="tab to file the level under (default: a new 自定义页签_N). "
                         "The editor groups levels into tabs, so this is part of the registration, "
                         "not decoration.")
    ap.add_argument("--level-id", type=int, default=None)
    ap.add_argument("--uid-dir", default=None, help="override the live save directory (for testing)")
    ap.add_argument("--stage", default=None,
                    help="write the candidates here (default: .runtime/beyond-save/candidates/<stamp>)")
    ap.add_argument("--apply", action="store_true",
                    help="ALSO write the live save. Takes a verified backup first. Not the default: "
                         "the live profile is the user's own save and a running game rewrites it.")
    args = ap.parse_args()
    if args.apply:
        require_compatible("all")  # Before staging, backups, or formal save access.

    plan = plan_registration(
        args.name, uid=args.uid, level_id=args.level_id,
        uid_dir=Path(args.uid_dir) if args.uid_dir else None,
        tab_name=args.tab,
    )
    print(json.dumps(plan.describe(), ensure_ascii=False, indent=1))

    stage_dir = Path(args.stage) if args.stage else (
        Path(__file__).resolve().parents[2] / ".runtime" / "beyond-save" / "candidates"
        / (time.strftime("%Y%m%dT%H%M%SZ", time.gmtime()) + f"-level-{plan.level_id}")
    )
    staged = stage_registration(plan, stage_dir)
    print(json.dumps({"staged": staged}, ensure_ascii=False, indent=1))

    if not args.apply:
        print(f"\nnothing written to the live save. To place the staged files:\n"
              f"  copy {staged['stagedLevel']} -> {plan.level_path.parent}\n"
              f"  copy {staged['stagedProfile']} -> {plan.profile_path}\n"
              f"or re-run with --apply to do both here, after taking a backup.")
        return 0

    backup = take_backup(plan)
    print(json.dumps({"backup": backup}, ensure_ascii=False, indent=1))
    result = apply_registration(plan)
    print(json.dumps({"registered": result}, ensure_ascii=False, indent=1))
    print(f"\nto undo: copy {backup['profile']} back over {plan.profile_path} and "
          f"remove {plan.level_path}")
    return 0


def main() -> int:
    try:
        return _main()
    except IncompatibleVersion as error:
        print(json.dumps(error.report, ensure_ascii=True))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
