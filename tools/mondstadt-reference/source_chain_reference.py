"""Bounded archive/source-chain audit; never executes upstream code or extracts paths.

inventory reads tar headers sequentially; extract accepts exact inventory names
and writes flat generated filenames under our own source workspace only.
"""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path, PurePosixPath
import tarfile

from reference_cli import digest, project_path, write_json
from regional_registration import ROOT, SOURCE, read, relative

WORK=SOURCE/'source-chain-v5'


def safe_member_name(name):
    p=PurePosixPath(name)
    if p.is_absolute() or '..' in p.parts or '\\' in name or '\x00' in name:
        return False
    return bool(p.parts)


def inventory(args):
    archive=WORK/'genshin.tar.xz';receipt=read(WORK/'archive-download.json')
    if archive.stat().st_size != 126520176 or digest(archive)!=receipt['sha256']:
        raise ValueError('Archive does not match locked download')
    target=WORK/'archive-inventory.json'
    if target.exists():raise ValueError('Archive inventory immutable')
    rows=[];total=0
    with tarfile.open(archive,mode='r|xz') as stream:
        for member in stream:
            if len(rows)>=20000:raise ValueError('Archive member limit exceeded')
            total+=member.size
            if total>4*1024**3:raise ValueError('Expanded logical archive exceeds 4GiB; stopped without extraction')
            rows.append({'name':member.name,'size':member.size,'type':member.type.decode('ascii','replace'),
                'regular':member.isfile(),'safeRelativeName':safe_member_name(member.name),
                'linkTarget':member.linkname or None})
    report={'schema':1,'archive':relative(archive),'archiveSha256':receipt['sha256'],
        'compressedBytes':archive.stat().st_size,'advertisedUncompressedFileBytes':total,'memberCount':len(rows),
        'inventoryComplete':True,'members':rows,'extensions':dict(Counter(PurePosixPath(r['name']).suffix.lower() for r in rows if r['regular'])),
        'noneExtracted':True,'noThirdPartyCodeExecuted':True}
    write_json(target,report);print(json.dumps({k:v for k,v in report.items() if k!='members'}))


def extract(args):
    """Read only exact requested regular members, assigning our own safe names."""
    requested=read(project_path(args.request))['members']
    names=[r['archiveName'] for r in requested]
    if len(set(names))!=len(names) or len(names)>40:raise ValueError('Bounded unique exact member requests required')
    inventory=read(WORK/'archive-inventory.json');lookup={r['name']:r for r in inventory['members']}
    for name in names:
        if name not in lookup or not lookup[name]['regular'] or not safe_member_name(name):raise ValueError('Unsafe/missing/nonregular member')
        if lookup[name]['size']>40*1024**2:raise ValueError('Selected member exceeds40MiB')
    if sum(lookup[n]['size'] for n in names)>160*1024**2:raise ValueError('Selected source batch exceeds160MiB')
    out=project_path(args.out)
    if not out.is_relative_to(WORK) or out.exists():raise ValueError('New owned source directory only')
    out.mkdir(parents=True);found=[]
    with tarfile.open(WORK/'genshin.tar.xz',mode='r|xz') as stream:
        for member in stream:
            if member.name not in names:continue
            req=requested[names.index(member.name)]
            ext=PurePosixPath(member.name).suffix.lower()
            # Prefix generated by list index; archive path never becomes output path.
            dst=out/(f'{names.index(member.name):02d}'+ext)
            body=stream.extractfile(member).read(member.size+1)
            if len(body)!=member.size:raise ValueError('Truncated selected member')
            dst.write_bytes(body)
            found.append({'archiveName':member.name,'purpose':req['purpose'],'path':relative(dst),'bytes':len(body),'sha256':digest(dst)})
    if len(found)!=len(names):raise ValueError('Not all exact members extracted')
    write_json(out/'members.json',{'schema':1,'archiveSha256':inventory['archiveSha256'],'members':found,'thirdPartyCodeExecuted':False})
    print(json.dumps(found))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('command',choices=['inventory','extract'])
    p.add_argument('--request');p.add_argument('--out');args=p.parse_args()
    {'inventory':inventory,'extract':extract}[args.command](args)
